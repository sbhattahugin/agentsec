"""Dummy-agent lab: starts every scenario in both modes and registers them as AgentSec targets.

    python demo/lab.py              # starts the dummy agents + mock platforms, writes targets/lab/*.yaml

Each custom target is a complete Agent -> MCP -> API + OAuth stack on its own ports (base 9100).
Mock platforms (base 9300) expose the same agents through the real platform APIs:
    Azure AI Foundry (engineering), Copilot Studio (hr), Microsoft 365 Copilot (engineering),
    plus static Atlassian Rovo (Forge manifest) targets.
"""
from __future__ import annotations

import argparse
import os
import sys
import time
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import platform_mocks as pm  # noqa: E402
from stack import SCENARIOS, Stack  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MODES = ["vulnerable", "hardened"]


def start(base_port: int = 9100, host: str = "127.0.0.1", out_dir: Path = ROOT / "targets" / "lab",
          log=print, platforms: bool = True, platform_port: int = 9300) -> list[Stack]:
    out_dir.mkdir(parents=True, exist_ok=True)
    stacks = []
    for i, scenario in enumerate(SCENARIOS):
        for j, mode in enumerate(MODES):
            p = base_port + (i * len(MODES) + j) * 10
            st = Stack(scenario, mode, host, agent_port=p, mcp_port=p + 1, api_port=p + 2).start()
            cfg = st.target_config()
            path = out_dir / f"{cfg['target']['name']}-{mode}.yaml"
            header = (f"# Generated by demo/lab.py - dummy '{scenario}' agent ({mode}).\n"
                      f"# Agent :{p}  MCP :{p + 1}  API+OAuth :{p + 2}\n")
            path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
            log(f"  {cfg['target']['name']:<18} {mode:<10} agent :{p}  mcp :{p + 1}  api :{p + 2}  -> {path.name}")
            stacks.append(st)
    if platforms:
        start_platforms(stacks, host, platform_port, out_dir, log)
    return stacks


def _write(path: Path, cfg: dict, header: str) -> None:
    path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")


def start_platforms(stacks: list[Stack], host: str, port: int, out_dir: Path, log=print) -> pm.Platforms:
    os.environ.setdefault(pm.SECRET_ENV, "demo-secret")  # secret of the mock tenant only
    by_key = {(s.scenario, s.mode): s for s in stacks}
    plat = pm.Platforms(by_key, host, port).start()
    assets = out_dir / "_assets"
    log(f"\nMock platforms: Entra+Graph :{port}  Foundry :{port + 1}  Copilot Studio :{port + 2}")
    note = (f"# Generated by demo/lab.py - mock platform target. Uses the mock Entra tenant at :{port};\n"
            f"# set {pm.SECRET_ENV}=demo-secret when scanning from the CLI.\n")
    for mode in MODES:
        made = []
        if ("engineering", mode) in by_key:
            st = by_key[("engineering", mode)]
            _write(out_dir / f"foundry-engineering-agent-{mode}.yaml", plat.foundry_target(st), note)
            pkg = pm.write_m365_package(assets / f"m365-engineering-{mode}", st)
            _write(out_dir / f"m365-engineering-agent-{mode}.yaml",
                   plat.m365_target(st, pkg.relative_to(out_dir).as_posix()), note)
            made += ["foundry-engineering-agent", "m365-engineering-agent"]
        if ("hr", mode) in by_key:
            _write(out_dir / f"copilot-studio-hr-agent-{mode}.yaml", plat.copilot_target(by_key[("hr", mode)]), note)
            made.append("copilot-studio-hr-agent")
        manifest = pm.write_forge_manifest(assets / f"rovo-{mode}", mode)
        _write(out_dir / f"rovo-jira-triage-agent-{mode}.yaml",
               pm.rovo_target(mode, manifest.relative_to(out_dir).as_posix()),
               "# Generated by demo/lab.py - Atlassian Rovo agent (static: Forge manifest only).\n")
        made.append("rovo-jira-triage-agent")
        log(f"  {mode:<10} {', '.join(made)}")
    return plat


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base-port", type=int, default=9100)
    p.add_argument("--platform-port", type=int, default=9300)
    p.add_argument("--no-platforms", action="store_true", help="Only start the custom HTTP agents")
    a = p.parse_args()
    print("Starting dummy agents:")
    stacks = start(a.base_port, platforms=not a.no_platforms, platform_port=a.platform_port)
    print("\nLab running. Scan e.g.:  agentsec scan targets/lab/hr-agent-vulnerable.yaml   (Ctrl+C to stop)")
    try:
        while True:
            time.sleep(3600)
    except KeyboardInterrupt:
        for st in stacks:
            st.stop()


if __name__ == "__main__":
    main()
