"""Dummy-agent lab: starts every scenario in both modes and registers them as AgentSec targets.

    python demo/lab.py              # starts 6 dummy agents, writes targets/lab/*.yaml, keeps running

Each target is a complete Agent -> MCP -> API + OAuth stack on its own ports (base 9100).
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from stack import SCENARIOS, Stack  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MODES = ["vulnerable", "hardened"]


def start(base_port: int = 9100, host: str = "127.0.0.1", out_dir: Path = ROOT / "targets" / "lab",
          log=print) -> list[Stack]:
    out_dir.mkdir(parents=True, exist_ok=True)
    stacks = []
    for i, scenario in enumerate(SCENARIOS):
        for j, mode in enumerate(MODES):
            p = base_port + (i * len(MODES) + j) * 10
            st = Stack(scenario, mode, host, agent_port=p, mcp_port=p + 1, api_port=p + 2).start()
            cfg = st.target_config()
            path = out_dir / f"{cfg['target']['name']}-{mode}.yaml"
            header = (f"# Generated by demo/lab.py - dummy '{scenario}' agent ({mode}).\n"
                      f"# Agent :{p}  MCP :{p + 1}  API+OAuth :{p + 2}\n")
            path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
            log(f"  {cfg['target']['name']:<18} {mode:<10} agent :{p}  mcp :{p + 1}  api :{p + 2}  -> {path.relative_to(ROOT)}")
            stacks.append(st)
    return stacks


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base-port", type=int, default=9100)
    a = p.parse_args()
    print("Starting dummy agents:")
    stacks = start(a.base_port)
    print("\nLab running. Scan e.g.:  agentsec scan targets/lab/hr-agent-vulnerable.yaml   (Ctrl+C to stop)")
    try:
        while True:
            time.sleep(3600)
    except KeyboardInterrupt:
        for st in stacks:
            st.stop()


if __name__ == "__main__":
    main()
